"""Release metadata helpers; app_info.py is the single version source."""

from __future__ import annotations

import argparse
import hashlib
import re
from pathlib import Path

from app_info import APP_NAME, APP_VERSION, CHECKSUM_ASSET_NAME, INSTALLER_ASSET_NAME

ROOT = Path(__file__).resolve().parent


def validate_version(tag: str | None = None) -> None:
    if not re.fullmatch(r"[0-9]{1,5}\.[0-9]{1,5}\.[0-9]{1,5}", APP_VERSION):
        raise ValueError("APP_VERSION must be a stable MAJOR.MINOR.PATCH version.")
    if tag is not None and tag != f"v{APP_VERSION}":
        raise ValueError(f"Tag {tag!r} does not match app_info.py (expected v{APP_VERSION}).")


def write_windows_version_info(path: Path | None = None) -> Path:
    validate_version()
    path = path or ROOT / "build" / "version_info.txt"
    path.parent.mkdir(parents=True, exist_ok=True)
    version = tuple(int(part) for part in APP_VERSION.split(".")) + (0,)
    text = f"""# Generated by release_tools.py; do not edit.
VSVersionInfo(
  ffi=FixedFileInfo(
    filevers={version!r}, prodvers={version!r}, mask=0x3f, flags=0x0,
    OS=0x40004, fileType=0x1, subtype=0x0, date=(0, 0)
  ),
  kids=[
    StringFileInfo([StringTable('040904B0', [
      StringStruct('CompanyName', '{APP_NAME}'),
      StringStruct('FileDescription', '{APP_NAME} download manager'),
      StringStruct('FileVersion', '{APP_VERSION}'),
      StringStruct('InternalName', '{APP_NAME}'),
      StringStruct('OriginalFilename', '{APP_NAME}.exe'),
      StringStruct('ProductName', '{APP_NAME}'),
      StringStruct('ProductVersion', '{APP_VERSION}')
    ])]),
    VarFileInfo([VarStruct('Translation', [1033, 1200])])
  ]
)
"""
    path.write_text(text, encoding="utf-8")
    return path


def release_notes(changelog: Path = ROOT / "CHANGELOG.md") -> str:
    text = changelog.read_text(encoding="utf-8")
    match = re.search(
        rf"^## {re.escape(APP_VERSION)}(?:[ \t].*)?\n(.*?)(?=^## |\Z)",
        text, re.MULTILINE | re.DOTALL,
    )
    if not match:
        raise ValueError(f"CHANGELOG.md has no entry for {APP_VERSION}.")
    return (
        f"# {APP_NAME} {APP_VERSION}\n\n{match.group(1).strip()}\n\n"
        f"## Install or update\n"
        f"Download **{INSTALLER_ASSET_NAME}** below and run it on Windows 10/11 x64. "
        "Python and the required download/media tools are included.\n\n"
        "Existing users can use **Help > Check for Updates**. Updates keep settings, "
        "history, and downloaded files. Windows may ask for administrator permission.\n\n"
        f"**Verification:** {CHECKSUM_ASSET_NAME} contains the installer's SHA-256. "
        "Unsigned releases may trigger a Windows SmartScreen warning; a checksum "
        "is an integrity check, not an Authenticode signature.\n\n"
        "Chrome/Edge require a one-time manual Load unpacked extension step. "
        "An updated unpacked extension may need Reload on the browser extensions page.\n"
    )


def write_release_files(
    installer: Path = ROOT / INSTALLER_ASSET_NAME,
    checksums: Path = ROOT / CHECKSUM_ASSET_NAME,
    notes: Path = ROOT / "dist" / "release" / "RELEASE_NOTES.md",
) -> str:
    validate_version()
    if installer.name != INSTALLER_ASSET_NAME:
        raise ValueError(f"The release installer must be named {INSTALLER_ASSET_NAME}.")
    with installer.open("rb") as handle:
        if handle.read(2) != b"MZ" or installer.stat().st_size < 1024 * 1024:
            raise ValueError("Build a valid Windows installer before generating its checksum.")
        handle.seek(0)
        digest = hashlib.file_digest(handle, "sha256").hexdigest()
    checksums.parent.mkdir(parents=True, exist_ok=True)
    checksums.write_text(f"{digest}  {INSTALLER_ASSET_NAME}\n", encoding="utf-8")
    notes.parent.mkdir(parents=True, exist_ok=True)
    notes.write_text(release_notes(), encoding="utf-8")
    return digest


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    commands = parser.add_subparsers(dest="command", required=True)
    commands.add_parser("version")
    validate = commands.add_parser("validate")
    validate.add_argument("--tag")
    commands.add_parser("resources")
    manifest = commands.add_parser("manifest")
    manifest.add_argument("--installer", type=Path, default=ROOT / INSTALLER_ASSET_NAME)
    args = parser.parse_args()
    try:
        if args.command == "version":
            validate_version()
            print(APP_VERSION)
        elif args.command == "validate":
            validate_version(args.tag)
            print(f"Release version validated: {APP_VERSION}")
        elif args.command == "resources":
            print(write_windows_version_info())
        elif args.command == "manifest":
            print(f"Installer SHA-256: {write_release_files(installer=args.installer)}")
    except (OSError, ValueError) as exc:
        parser.exit(1, f"ERROR: {exc}\n")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
